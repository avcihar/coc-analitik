export const WALL_LEVELS: WallAssetConfig[] = Array.from({ length: 20 }, (_, i) => {
  const level = i + 1;
  const thLevel = WALL_TH_BY_LEVEL[level] ?? 19;
  return {
    id: `wall${level}`,
    level,
    thLevel,
    name: `Seviye ${level} Duvar (BB${thLevel})`,
    src: `/walls/Wall${level}.webp`,
    middleSrc: level <= 18 ? `/walls/Wall${level}_Middle.webp` : undefined,
    connectorColors: WALL_CONNECTOR_PALETTES[level],
    naturalWidth: 100,
    naturalHeight: 120,
  };
});

export function getWallConfig(level: number): WallAssetConfig {
  const clamped = Math.max(1, Math.min(20, Math.round(level || 20)));
  return WALL_LEVELS[clamped - 1] || WALL_LEVELS[WALL_LEVELS.length - 1];
}

/**
 * Localize scenery display name cleanly while preserving static measured configs.
 */
export function getSceneryDisplayName(
  id: string,
  fallbackName: string,
  locale: "tr" | "en" = "tr"
): string {
  if (id === "winter") {
    return locale === "tr" ? "Kış Sahnesi (Winter)" : "Winter Scenery";
  }
  return fallbackName;
}

