export interface BuildAreaCorners {
  top: { x: number; y: number };
  right: { x: number; y: number };
  bottom: { x: number; y: number };
  left: { x: number; y: number };
}

export interface SceneryAssetConfig {
  id: string;
  name: string;
  src: string;
  thumb: string;
  naturalWidth: number;
  naturalHeight: number;
  buildArea: BuildAreaCorners;
  wall?: string;
  verified?: boolean;
  status?: "Doğrulandı" | "Elle düzeltildi" | "Güvenilmez";
  method?: "calibrated" | "tile-pattern" | "manual" | "none";
  reason?: string;
}

export interface WallAssetConfig {
  id: string;
  name: string;
  src: string;
  naturalWidth: number;
  naturalHeight: number;
}

/**
 * Localize scenery display name cleanly while preserving static measured configs.
 */
export function getSceneryDisplayName(
  id: string,
  fallbackName: string,
  locale: "tr" | "en" = "tr"
): string {
  if (id === "winter") {
    return locale === "tr" ? "Kış Sahnesi (Winter)" : "Winter Scenery";
  }
  return fallbackName;
}

