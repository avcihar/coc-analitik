REQUIRED_CHARS = (
    [chr(c) for c in range(65, 91)]
    + ["Ç", "Ğ", "İ", "Ö", "Ş", "Ü"]
    + [chr(c) for c in range(97, 123)]
    + ["ç", "ğ", "ı", "ö", "ş", "ü"]
    + [str(d) for d in range(10)]
    + [" ", "(", ")", "!", "?", ".", ",", "-", "_", "+", ":", ";", "/", "#", "&", "@", "*"]
)


def parse_ascii_glyph(rows, expected_h):
    assert len(rows) == expected_h, f"Expected {expected_h} rows, got {len(rows)}"
    w = len(rows[0])
    assert w > 0, "Empty glyph width"
    mat = []
    for r in rows:
        assert len(r) == w, f"Inconsistent row width {len(r)} != {w}: {rows}"
        mat.append([1 if ch == "#" else 0 for ch in r])
    return mat


def validate_font_glyphs(glyphs, expected_h=None):
    missing = [ch for ch in REQUIRED_CHARS if ch not in glyphs]
    assert not missing, f"Missing required chars: {missing}"
    for ch, mat in glyphs.items():
        if expected_h is not None:
            assert len(mat) == expected_h, f"{ch}: height {len(mat)} != {expected_h}"
        w = len(mat[0])
        for row in mat:
            assert len(row) == w, f"{ch}: non-rectangular row"


def pad_or_crop_top_bottom(mat, target_h, pad_top=0, pad_bottom=0):
    w = len(mat[0])
    res = [[0] * w for _ in range(pad_top)] + [row[:] for row in mat] + [[0] * w for _ in range(pad_bottom)]
    assert len(res) == target_h, f"Expected {target_h}, got {len(res)}"
    return res


def scale_matrix_nn(mat, target_h, target_w):
    """Nearest-neighbor integer grid resampling for crisp proportional adaptation."""
    src_h = len(mat)
    src_w = len(mat[0])
    out = []
    for r in range(target_h):
        sr = min(src_h - 1, (r * src_h) // target_h)
        row = []
        for c in range(target_w):
            sc = min(src_w - 1, (c * src_w) // target_w)
            row.append(mat[sr][sc])
        out.append(row)
    return out


