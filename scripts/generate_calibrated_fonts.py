# 4. COMPLETE EXISTING FONTS (preserving all original glyphs & normalized metrics)
# ==============================================================================
def complete_cross_stitch():
    path = os.path.join(FONTS_DIR, "cross_stitch.json")
    with open(path, "r", encoding="utf-8") as fp:
        data = json.load(fp)

    orig_upper = set("ABCDEFGHIJKLMNOPQRSTUVWXYZ")
    preserved = {k: v for k, v in data.items() if k in orig_upper}
    assert len(preserved) == 26, "cross_stitch.json missing original A-Z glyphs"

    # Normalized cross_stitch is H=13 (rows 0..12), baseline=11:
    # row 0: upper diacritic, rows 1..11: cap height (11 rows), row 12: descender/cedilla.
    bold = build_clash_bold()["glyphs"]
    block = build_clash_block()["glyphs"]

    new_glyphs = {}
    new_baselines = {"Q": 10, "R": 10}

    def put_cedilla_on_orig(base_ch):
        # Original A-Z (except Q, R, W, Y) are 11 rows tall (rows 1..11 in normalized space)
        m = [row[:] for row in preserved[base_ch]]
        w = len(m[0])
        mid = w // 2
        row11 = [0] * w
        row12 = [0] * w
        row11[mid] = 1
        if mid + 1 < w:
            row11[mid + 1] = 1
        if mid - 1 >= 0:
            row12[mid - 1] = 1
        row12[mid] = 1
        # Store as 13-row matrix with baseline=11 (row 0 blank, 1..11 body, 12 descender)
        return [[0] * w] + m + [row12]  # Wait: let's keep row 11 body + row 12 cedilla:
        # Actually m[10] is row 11 (baseline), so [0]*w + m + [row12] puts body on rows 1..11 and cedilla on row 12!

    # Turkish Uppercase (stored at H=13 with baseline=11)
    for ch, base_ch in [("Ç", "C"), ("Ş", "S")]:
        m = [row[:] for row in preserved[base_ch]]
        w = len(m[0])
        mid = w // 2
        desc = [0] * w
        desc[mid] = 1
        if mid - 1 >= 0:
            desc[mid - 1] = 1
        new_glyphs[ch] = [[0] * w] + m + [desc]
        new_baselines[ch] = 11

    # For Ğ, İ, Ö, Ü: keep row 0 as diacritic, row 1 blank, rows 2..11 as 10-row cap (preserving top & bottom serifs!), row 12 blank
    for ch, base_ch, mark_type in [("Ğ", "G", "breve"), ("İ", "I", "dot"), ("Ö", "O", "umlaut"), ("Ü", "U", "umlaut")]:
        base = preserved[base_ch]
        w = len(base[0])
        # Keep top row (0), drop row 3 (vertical stem repeat), keep rows 1,2,4..10 -> 10 rows total with bottom serif intact
        body_10 = [row[:] for row in (base[:3] + base[4:])]
        assert len(body_10) == 10
        mark_row = [0] * w
        if mark_type == "dot":
            for c in range(max(0, w // 2 - 1), min(w, w // 2 + 1)):
                mark_row[c] = 1
        elif mark_type == "umlaut":
            mark_row[max(0, w // 2 - 2)] = 1
            mark_row[max(0, w // 2 - 1)] = 1
            mark_row[min(w - 1, w // 2 + 1)] = 1
            mark_row[min(w - 1, w // 2 + 2)] = 1
        elif mark_type == "breve":
            for c in range(max(0, w // 2 - 2), min(w, w // 2 + 3)):
                mark_row[c] = 1
            mark_row[w // 2] = 0
        mat = [mark_row, [0] * w] + body_10 + [[0] * w]
        new_glyphs[ch] = mat
        new_baselines[ch] = 11

    # Lowercase, digits, space, symbols adapted cleanly into 13-row (rows 1..11 cap, 5..11 x-height, 12 descender)
    for ch in REQUIRED_CHARS:
        if ch in preserved or ch in new_glyphs:
            continue
        src = block[ch]  # 12 rows: 0..1 marks, 2..9 caps, 10..11 descenders
        w = len(src[0])
        out_w = max(3, min(11, w + (1 if w >= 6 else 0)))
        if ch == " ":
            mat = [[0] * 4 for _ in range(13)]
        elif ch in "0123456789()!?.-_+:;/#&@*":
            if ch in ",;":
                body = scale_matrix_nn(src[2:10], 11, out_w)
                tail = scale_matrix_nn(src[10:12], 1, out_w)
                mat = [[0] * out_w] + body + tail
            else:
                body = scale_matrix_nn(src[2:10], 11, out_w)
                mat = [[0] * out_w] + body + [[0] * out_w]
        elif ch in "gjpqy":
            # 4..9 -> 5..11 (7 rows), 10..11 -> row 12
            body = scale_matrix_nn(src[4:10], 7, out_w)
            tail = scale_matrix_nn(src[10:12], 1, out_w)
            mat = [[0] * out_w for _ in range(5)] + body + tail
        elif ch in "çş":
            body = scale_matrix_nn(src[4:10], 7, out_w)
            tail = scale_matrix_nn(src[10:12], 1, out_w)
            mat = [[0] * out_w for _ in range(5)] + body + tail
        elif ch == "ğ":
            mark = scale_matrix_nn(src[1:3], 2, out_w)
            body = scale_matrix_nn(src[4:10], 7, out_w)
            tail = scale_matrix_nn(src[10:12], 1, out_w)
            mat = [[0] * out_w] + mark + [[0] * out_w, [0] * out_w] + body + tail
        elif ch in "öü":
            mark = scale_matrix_nn(src[1:2], 2, out_w)
            body = scale_matrix_nn(src[4:10], 7, out_w)
            mat = [[0] * out_w] + mark + [[0] * out_w, [0] * out_w] + body + [[0] * out_w]
        elif ch in "ij":
            dot = scale_matrix_nn(src[2:3], 2, out_w)
            body = scale_matrix_nn(src[4:10], 7, out_w)
            tail = scale_matrix_nn(src[10:12], 1, out_w) if ch == "j" else [[0] * out_w]
            mat = [[0] * out_w] + dot + [[0] * out_w, [0] * out_w] + body + tail
        elif ch in "bdfhklt":
            body = scale_matrix_nn(src[2:10], 11, out_w)
            mat = [[0] * out_w] + body + [[0] * out_w]
        else:
            # standard lowercase x-height 4..9 -> rows 5..11
            body = scale_matrix_nn(src[4:10], 7, out_w)
            mat = [[0] * out_w for _ in range(5)] + body + [[0] * out_w]
        new_glyphs[ch] = mat
        new_baselines[ch] = 11

    out_data = {"_meta": {"baselines": new_baselines}}
    for k, v in preserved.items():
        out_data[k] = v
    for k, v in new_glyphs.items():
        out_data[k] = v

    all_g = {k: v for k, v in out_data.items() if k != "_meta"}
    validate_font_glyphs(all_g)
    with open(path, "w", encoding="utf-8") as fp:
        json.dump(out_data, fp, ensure_ascii=False, indent=2)
    print(f"Updated {path} ({len(all_g)} glyphs, preserved 26 originals)")


def complete_tango_stitch():
    path = os.path.join(FONTS_DIR, "tango_stitch.json")
    with open(path, "r", encoding="utf-8") as fp:
        data = json.load(fp)

    orig_keys = set(
        [chr(c) for c in range(65, 91)]
        + [chr(c) for c in range(97, 123)]
        + [str(d) for d in range(10)]
    )
    preserved = {k: v for k, v in data.items() if k in orig_keys}
    assert len(preserved) == 62, "tango_stitch.json missing original 62 glyphs"

    block = build_clash_block()["glyphs"]
    new_glyphs = {}

    def add_cedilla_tango(base_ch):
        m = [row[:] for row in preserved[base_ch]]
        w = len(m[0])
        mid = w // 2
        for c in range(max(0, mid - 1), min(w, mid + 1)):
            m[12][c] = 1
        m[13][mid] = 1
        if mid + 1 < w:
            m[13][mid + 1] = 1
        for c in range(max(0, mid - 1), min(w, mid + 1)):
            m[14][c] = 1
        return m

    new_glyphs["Ç"] = add_cedilla_tango("C")
    new_glyphs["Ş"] = add_cedilla_tango("S")
    new_glyphs["ç"] = add_cedilla_tango("c")
    new_glyphs["ş"] = add_cedilla_tango("s")

    # Dotless i -> ı
    m_i = [row[:] for row in preserved["i"]]
    for r in range(4):
        m_i[r] = [0] * len(m_i[0])
    new_glyphs["ı"] = m_i

    # Uppercase Ö (O already occupies rows 2..11!)
    m_O = [row[:] for row in preserved["O"]]
    wO = len(m_O[0])
    m_O[0][1] = 1
    m_O[0][2] = 1
    m_O[0][wO - 3] = 1
    m_O[0][wO - 2] = 1
    new_glyphs["Ö"] = m_O

    # Uppercase Ğ, İ, Ü (10-row body on rows 2..11 keeping top & bottom serifs intact, blank row 1, mark on row 0)
    for ch, base_ch, mtype in [("Ğ", "G", "breve"), ("İ", "I", "dot"), ("Ü", "U", "umlaut")]:
        base = preserved[base_ch]
        w = len(base[0])
        body_10 = [row[:] for row in (base[1:5] + base[6:12])]
        assert len(body_10) == 10
        out = [[0] * w for _ in range(16)]
        for r in range(10):
            out[2 + r] = body_10[r]
        if mtype == "dot":
            for c in range(max(0, w // 2 - 1), min(w, w // 2 + 1)):
                out[0][c] = 1
        elif mtype == "umlaut":
            out[0][1] = 1
            out[0][2] = 1
            out[0][w - 3] = 1
            out[0][w - 2] = 1
        elif mtype == "breve":
            out[0][max(0, w // 2 - 2)] = 1
            out[0][max(0, w // 2 - 1)] = 1
            out[0][min(w - 1, w // 2 + 1)] = 1
            out[0][min(w - 1, w // 2 + 2)] = 1
        new_glyphs[ch] = out

    # Lowercase ğ, ö, ü (body rows 4..11 / 4..14, blank row 3, marks rows 1..2)
    for ch, base_ch, mtype in [("ğ", "g", "breve"), ("ö", "o", "umlaut"), ("ü", "u", "umlaut")]:
        m = [row[:] for row in preserved[base_ch]]
        w = len(m[0])
        if mtype == "umlaut":
            m[1][1] = 1
            m[2][1] = 1
            m[1][w - 2] = 1
            m[2][w - 2] = 1
        else:
            m[1][1] = 1
            m[1][w - 2] = 1
            for c in range(2, w - 2):
                m[2][c] = 1
        new_glyphs[ch] = m

    # Space + symbols (H=16, baseline=15, main zone rows 1..11, descenders 12..14)
    for ch in REQUIRED_CHARS:
        if ch in preserved or ch in new_glyphs:
            continue
        if ch == " ":
            new_glyphs[ch] = [[0] * 4 for _ in range(16)]
            continue
        src = block[ch]
        w = len(src[0])
        out_w = max(2, min(9, w))
        out = [[0] * out_w for _ in range(16)]
        if ch in ",;":
            body = scale_matrix_nn(src[2:10], 11, out_w)
            tail = scale_matrix_nn(src[10:12], 3, out_w)
            for r in range(11):
                out[1 + r] = body[r]
            for r in range(3):
                out[12 + r] = tail[r]
        else:
            body = scale_matrix_nn(src[2:10], 11, out_w)
            for r in range(11):
                out[1 + r] = body[r]
        new_glyphs[ch] = out

    out_data = {}
    for k, v in preserved.items():
        out_data[k] = v
    for k, v in new_glyphs.items():
        out_data[k] = v

    validate_font_glyphs(out_data, 16)
    with open(path, "w", encoding="utf-8") as fp:
        json.dump(out_data, fp, ensure_ascii=False, indent=2)
    print(f"Updated {path} ({len(out_data)} glyphs, preserved 62 originals)")


def complete_plastic_canvas():
    path = os.path.join(FONTS_DIR, "plastic_canvas.json")
    with open(path, "r", encoding="utf-8") as fp:
        data = json.load(fp)

    orig_lower = set("abcdefghijklmnopqrstuvwxyz")
    preserved = {k: v for k, v in data.items() if k in orig_lower}
    assert len(preserved) == 26, "plastic_canvas.json missing original a-z glyphs"

    # Normalized plastic_canvas is H=23 (rows 0..22):
    # 0..5 ascender/diacritic zone, 6..14 x-height (9 rows), 1..14 caps (14 rows), 15..22 descenders.
    block = build_clash_block()["glyphs"]
    new_glyphs = {}

    # Turkish lowercase from existing a-z
    for ch, base_ch in [("ç", "c"), ("ş", "s")]:
        m = [row[:] for row in preserved[base_ch]]
        w = len(m[0])
        mid = w // 2
        for r in (15, 16):
            m[r][mid] = 1
        m[17][mid] = 1
        if mid + 1 < w:
            m[17][mid + 1] = 1
        for c in range(max(0, mid - 1), min(w, mid + 2)):
            m[18][c] = 1
        new_glyphs[ch] = m

    m_i = [row[:] for row in preserved["i"]]
    for r in range(5):
        m_i[r] = [0] * len(m_i[0])
    new_glyphs["ı"] = m_i

    for ch, base_ch in [("ö", "o"), ("ü", "u")]:
        m = [row[:] for row in preserved[base_ch]]
        w = len(m[0])
        for r in (2, 3):
            m[r][1] = 1
            m[r][2] = 1
            m[r][w - 3] = 1
            m[r][w - 2] = 1
        new_glyphs[ch] = m

    # Clean ğ based on g body (rows 7..22) + breve (rows 2..3)
    m_g = [row[:] for row in preserved["g"]]
    for r in range(6):
        m_g[r] = [0] * len(m_g[0])
    wg = len(m_g[0])
    m_g[2][1] = 1
    m_g[2][wg - 2] = 1
    for c in range(2, wg - 2):
        m_g[3][c] = 1
    new_glyphs["ğ"] = m_g

    # Uppercase A-Z, Ç, Ğ, İ, Ö, Ş, Ü, Digits 0-9, Space, Symbols (all H=23)
    for ch in REQUIRED_CHARS:
        if ch in preserved or ch in new_glyphs:
            continue
        if ch == " ":
            new_glyphs[ch] = [[0] * 5 for _ in range(23)]
            continue
        src = block[ch]
        w = len(src[0])
        out_w = max(2, round(w * 1.25))
        out = [[0] * out_w for _ in range(23)]
        if ch in "ÇŞ":
            body = scale_matrix_nn(src[2:10], 14, out_w)
            tail = scale_matrix_nn(src[10:12], 4, out_w)
            for r in range(14):
                out[1 + r] = body[r]
            for r in range(4):
                out[15 + r] = tail[r]
        elif ch in "ĞİÖÜ":
            mark = scale_matrix_nn(src[0:2], 2, out_w)
            body = scale_matrix_nn(src[2:10], 12, out_w)
            for r in range(2):
                out[r] = mark[r]
            for r in range(12):
                out[3 + r] = body[r]
        elif ch in ",;":
            body = scale_matrix_nn(src[2:10], 14, out_w)
            tail = scale_matrix_nn(src[10:12], 4, out_w)
            for r in range(14):
                out[1 + r] = body[r]
            for r in range(4):
                out[15 + r] = tail[r]
        elif ch == "Q":
            body = scale_matrix_nn(src[2:10], 14, out_w)
            tail = scale_matrix_nn(src[10:12], 4, out_w)
            for r in range(14):
                out[1 + r] = body[r]
            for r in range(4):
                out[15 + r] = tail[r]
        else:
            body = scale_matrix_nn(src[2:10], 14, out_w)
            for r in range(14):
                out[1 + r] = body[r]
        new_glyphs[ch] = out

    out_data = {}
    for k, v in preserved.items():
        out_data[k] = v
    for k, v in new_glyphs.items():
        out_data[k] = v

    validate_font_glyphs(out_data, 23)
    with open(path, "w", encoding="utf-8") as fp:
        json.dump(out_data, fp, ensure_ascii=False, indent=2)
    print(f"Updated {path} ({len(out_data)} glyphs, preserved 26 originals)")


